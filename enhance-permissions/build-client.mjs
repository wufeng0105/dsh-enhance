#!/usr/bin/env node
/**
 * 从宿主自带的权限选择器 bundle 派生出 `client.js`。
 *
 * 宿主的选择器按预设的**值**（read-only / workspace-write / danger-full-access / auto）
 * 查一张封闭的字形表，所以自定义档位没有图标。那张表封在 asar 里，
 * `conversation.input.permission` 槽位又是 `kind: 'single'`，唯一能给自定义档位加图标的办法，
 * 是用本包名再发一份那个 bundle。
 *
 * 本脚本只对宿主产物做两处文本补丁，并断言两处都命中：
 *   1. 注册 id 改成当前包名；
 *   2. `permissionGlyphs` 里加一条：`enhanced` → 盾牌 + 闪电。
 *
 * 同时把来源 bundle 的 `source-sha256` 写进文件头。`--check` 靠这个戳判断代际：
 * 指向另一份 asar（旧的 `_artifacts`，或升级后的新版本）会报「来自另一代」而不是静默通过——
 * 「能加载但行为变了」正是要挡的那种失败。
 *
 * DSH 升级后必须重跑（来源 bundle 与宿主版本耦合）。
 *
 * 用法：node build-client.mjs --asar <app.asar> [--out client.js] [--check]
 *       node build-client.mjs --app <resources/app> [--out client.js]
 *
 * `--check` 不写盘：在内存里重新派生再和盘上的比，不一致就 exit 1。升级冒烟用它——
 * 一次 `--check` 就能回答「这份派生件要不要重派生」。
 *
 * `--app` 在拿不到 asar 的机器上回答同一个代际问题（解包安装、或只有 `resources/app`）：
 * 算已装 bundle 的摘要再和 `client.js` 里的戳比。它比 `--check` 弱——只证明「同一份源码」，
 * 不证明「补丁还落得下」——所以是 asar 路径的兜底而不是替代，同样不写盘。
 */

import { createHash } from 'node:crypto'
import { openSync, readFileSync, readSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

/** Package name this bundle registers as; must equal package.json's `name`. */
const PACKAGE_NAME = 'dsh-enhance-permissions'

/** Shipped bundle this copy derives from. */
const SOURCE_ENTRY = '/dsh/node_modules/@deepseek-ai/dsh-client-ui-permission-presets/lib/client.js'

/** Shield silhouette shared by the shipped permission icons (16×16 viewBox). */
const SHIELD = 'M6.59624 2.14853C7.50155 1.80917 8.49914 1.80919 9.40444 2.14859L13.9245 3.84317V7.11961C13.9245 11.6089 10.5565 13.5975 8.00035 14.5779C5.44423 13.5975 2.07544 11.6089 2.07544 7.11961V3.84317L6.59624 2.14853Z'
/** Bolt inside the shield: "enhanced" rather than the shipped lock or plus. */
const BOLT = 'M8.9 4.4L6.2 8.9H7.9L7.1 11.6L9.8 7.1H8.1L8.9 4.4Z'

function extract(archive, wanted) {
  const handle = openSync(archive, 'r')
  const header = Buffer.alloc(8)
  readSync(handle, header, 0, 8, 0)
  const headerSize = header.readUInt32LE(4)
  const body = Buffer.alloc(headerSize)
  readSync(handle, body, 0, headerSize, 8)
  const indexSize = body.readUInt32LE(4)
  const index = JSON.parse(body.toString('utf8', 8, 8 + indexSize))
  const base = 8 + headerSize
  let found
  const walk = (node, prefix) => {
    for (const [name, child] of Object.entries(node.files ?? {})) {
      const path = `${prefix}/${name}`
      if (child.files) walk(child, path)
      else if (path === wanted) found = child
    }
  }
  walk(index, '')
  if (found === undefined) throw new Error(`not found in archive: ${wanted}`)
  const bytes = Buffer.alloc(found.size)
  readSync(handle, bytes, 0, found.size, base + Number(found.offset))
  return bytes.toString('utf8')
}

/** Replace one exact occurrence and fail when the artifact no longer matches. */
function patch(text, from, to, label) {
  const first = text.indexOf(from)
  if (first < 0) throw new Error(`patch target missing: ${label} (the shipped bundle changed; re-derive this script)`)
  if (text.indexOf(from, first + 1) >= 0) throw new Error(`patch target ambiguous: ${label}`)
  return text.slice(0, first) + to + text.slice(first + from.length)
}

/** Header that records which generation of the shipped bundle this copy came from. */
function header(sourceSha) {
  return [
    `// ${PACKAGE_NAME} — generated by enhance/enhance-permissions/build-client.mjs; do not edit.`,
    `// source: ${SOURCE_ENTRY}`,
    `// source-sha256: ${sourceSha}`,
    '',
  ].join('\n')
}

/** The `source-sha256:` a file claims, if any. */
function claimedSourceSha(text) {
  const match = /^\/\/ source-sha256: ([0-9a-f]{64})$/m.exec(text)
  return match === null ? undefined : match[1]
}

/** `<resources/app>` → the shipped bundle, addressed by the same path the asar uses. */
function appBundlePath(app) {
  return join(app, ...SOURCE_ENTRY.split('/').filter((segment) => segment !== ''))
}

/**
 * Generation check against an unpacked install: hash the installed bundle, then
 * compare that digest with the `source-sha256` stamp the copy on disk claims.
 *
 * Returns an exit code instead of throwing, so a missing path is one line rather
 * than a stack. Never writes.
 */
function checkApp(app, out) {
  const bundle = appBundlePath(app)
  let shipped
  try {
    shipped = readFileSync(bundle, 'utf8')
  } catch (error) {
    const state = error?.code === 'ENOENT' || error?.code === 'ENOTDIR' ? 'not found' : `unreadable code=${error?.code ?? 'unknown'}`
    console.error(`check=app-error bundle=${state} path=${bundle} · 装好的 resources/app 里没有这份 bundle`)
    return 1
  }
  let current
  try {
    current = readFileSync(out, 'utf8')
  } catch {
    console.error(`check=missing out=${out} · 先跑一次不带 --check 的派生`)
    return 1
  }
  const claimed = claimedSourceSha(current)
  if (claimed === undefined) {
    console.error(`check=stamp-missing out=${out} · 派生物没有 source-sha256 戳（旧版脚本产物）：重派生`)
    return 1
  }
  const actual = createHash('sha256').update(shipped, 'utf8').digest('hex')
  if (claimed !== actual) {
    console.error(`check=DIFFERS out=${out} on_disk=${claimed.slice(0, 12)} app=${actual.slice(0, 12)} bundle=${bundle} · 派生物与这份 app 不同代，对新 bundle 重派生`)
    return 1
  }
  console.log(`check=same-generation out=${out} source_sha256=${actual.slice(0, 12)} bundle=${bundle}`)
  return 0
}

function derive(asar) {
  const shipped = extract(asar, SOURCE_ENTRY)
  const sourceSha = createHash('sha256').update(shipped, 'utf8').digest('hex')
  let text = patch(shipped, 'id: "@deepseek-ai/dsh-client-ui-permission-presets"', `id: "${PACKAGE_NAME}"`, 'registration id')

  const glyphAnchor = '[AUTO_REVIEW_PRESET, (0, react_jsx_runtime.jsx)(_deepseek_ai_dsh_client_ui_primitives.PermissionIconAutoReviewRegular, {})]'
  const glyphEntry = `[AUTO_REVIEW_PRESET, (0, react_jsx_runtime.jsx)(_deepseek_ai_dsh_client_ui_primitives.PermissionIconAutoReviewRegular, {})],
["enhanced", (0, react_jsx_runtime.jsx)("svg", { width: 16, height: 16, viewBox: "0 0 16 16", fill: "none", xmlns: "http://www.w3.org/2000/svg", "aria-hidden": "true", children: [(0, react_jsx_runtime.jsx)("path", { d: "${SHIELD}", stroke: "currentColor", strokeLinejoin: "round" }), (0, react_jsx_runtime.jsx)("path", { d: "${BOLT}", fill: "currentColor" })] })]`
  text = patch(text, glyphAnchor, glyphEntry, 'glyph map')

  if (!text.includes(PACKAGE_NAME) || !text.includes('"enhanced"')) throw new Error('derived bundle lost a patch')
  return { text: header(sourceSha) + text, sourceSha }
}

/**
 * Value of a flag, or a usage error. Without this a missing value reaches
 * `resolve(undefined)` and dies as a `node:path` TypeError — a stack that tells
 * the user nothing about which flag they left empty.
 */
function valueOf(argv, index, flag) {
  const value = argv[index + 1]
  if (typeof value !== 'string' || value.trim() === '') throw new Error(`${flag} 需要一个值`)
  return value
}

function parseArgs(argv) {
  const options = { app: undefined, asar: undefined, out: undefined, check: false }
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (arg === '--check') options.check = true
    else if (arg === '--app') { options.app = valueOf(argv, index, '--app'); index += 1 }
    else if (arg === '--asar') { options.asar = valueOf(argv, index, '--asar'); index += 1 }
    else if (arg === '--out') { options.out = valueOf(argv, index, '--out'); index += 1 }
    else throw new Error(`未知参数：${arg}`)
  }
  return options
}

let options
try {
  options = parseArgs(process.argv.slice(2))
} catch (error) {
  console.error(`build-client: ${String(error?.message ?? error)}`)
  process.exit(1)
}

const out = options.out === undefined ? join(dirname(fileURLToPath(import.meta.url)), 'client.js') : resolve(options.out)

// `--app` is the asar-less path and takes over only when `--asar` is absent, so
// every existing `--asar` invocation keeps its exact argv meaning.
if (options.app !== undefined && options.asar === undefined) {
  process.exit(checkApp(resolve(options.app), out))
}

if (options.asar === undefined) {
  console.error('build-client: 用法：node build-client.mjs --asar <app.asar> [--out client.js] [--check] | --app <resources/app>')
  process.exit(1)
}

const asar = resolve(options.asar)
const { text, sourceSha } = derive(asar)

if (options.check) {
  let current
  try {
    current = readFileSync(out, 'utf8')
  } catch {
    console.error(`check=missing out=${out} · 先跑一次不带 --check 的派生`)
    process.exit(1)
  }
  const same = current === text
  console.log(`check=${same ? 'identical' : 'DIFFERS'} out=${out} derived_bytes=${byteLength(text)} on_disk_bytes=${byteLength(current)} source_sha256=${sourceSha.slice(0, 12)}`)
  if (!same) {
    const claimed = claimedSourceSha(current)
    if (claimed === undefined) console.error('reason=派生物没有 source-sha256 戳（旧版脚本产物）：重派生')
    else if (claimed !== sourceSha) console.error(`reason=派生物来自另一份 asar：on_disk=${claimed.slice(0, 12)} asar=${sourceSha.slice(0, 12)}（版本不同代，必须对新 asar 重派生）`)
    else console.error('reason=同一代 asar，但补丁或脚本文本已变：重派生')
    process.exit(1)
  }
  process.exit(0)
}

writeFileSync(out, text)
console.log(`derived ${out} from ${SOURCE_ENTRY} bytes=${byteLength(text)} source_sha256=${sourceSha.slice(0, 12)}`)
function byteLength(value) {
  return Buffer.byteLength(value, 'utf8')
}
